/*
 * Baysöz Yazılım — NAZTECH Bilişim browser hardening layer.
 * Contact: baysozlabs@proton.me
 *
 * Classic deferred script. It suppresses developer-tool shortcuts, blocks
 * image dragging, runs the 1.5s golden circuit scan before an official
 * download hand-off, and removes machine-authored comments from the live DOM.
 */

(function () {
  "use strict";

  var SCAN_DURATION_MS = 1500;
  var COMMENT_MARKER = /\b(?:ai|agent|copilot|chatgpt|claude|opencode)\b|generated by/i;
  var host = typeof window !== "undefined" ? window : (typeof globalThis !== "undefined" ? globalThis : {});
  var doc = typeof document !== "undefined" ? document : null;
  var scanModal = doc ? doc.getElementById("downloadScanModal") : null;
  var scanPanel = scanModal ? scanModal.querySelector(".scan-modal__panel") : null;
  var scanStatus = doc ? doc.getElementById("scanStatus") : null;
  var scanTimer = null;
  var pendingUrl = "";
  var previousFocus = null;

  function addListener(target, type, handler) {
    if (target && typeof target.addEventListener === "function") {
      target.addEventListener(type, handler, true);
    }
  }

  function schedule(callback, delay) {
    if (typeof host.setTimeout === "function") {
      return host.setTimeout(callback, delay);
    }
    return setTimeout(callback, delay);
  }

  function unschedule(timer) {
    if (timer === null || timer === undefined) {
      return;
    }
    if (typeof host.clearTimeout === "function") {
      host.clearTimeout(timer);
      return;
    }
    clearTimeout(timer);
  }

  function isScanning() {
    return scanTimer !== null && scanTimer !== undefined;
  }

  function restoreFocus() {
    if (previousFocus && typeof previousFocus.focus === "function") {
      previousFocus.focus();
    }
    previousFocus = null;
  }

  function hideScan() {
    if (scanModal) {
      scanModal.hidden = true;
      scanModal.setAttribute("aria-hidden", "true");
    }
    if (doc && doc.body && typeof doc.body.classList.remove === "function") {
      doc.body.classList.remove("is-scanning");
    }
    scanTimer = null;
    pendingUrl = "";
  }

  function openTarget(url) {
    if (!url || /^https:\/\//i.test(url) !== true) {
      return;
    }
    if (doc && typeof doc.createElement === "function") {
      var anchor = doc.createElement("a");
      anchor.setAttribute("href", url);
      anchor.setAttribute("target", "_blank");
      anchor.setAttribute("rel", "noopener noreferrer");
      if (typeof anchor.click === "function") {
        anchor.click();
        return;
      }
    }
    if (typeof host.open === "function") {
      host.open(url, "_blank", "noopener,noreferrer");
      return;
    }
    if (host.location && typeof host.location.assign === "function") {
      host.location.assign(url);
    }
  }

  function completeScan() {
    if (!isScanning()) {
      return;
    }
    var target = pendingUrl;
    hideScan();
    restoreFocus();
    openTarget(target);
  }

  function cancelScan() {
    if (!isScanning()) {
      return;
    }
    unschedule(scanTimer);
    hideScan();
    restoreFocus();
  }

  function startScan(trigger) {
    if (!scanModal || !trigger || isScanning()) {
      return false;
    }
    var url = trigger.getAttribute("data-download-url") || "";
    if (/^https:\/\//i.test(url) !== true) {
      return false;
    }

    pendingUrl = url;
    previousFocus = doc.activeElement || null;
    scanModal.hidden = false;
    scanModal.setAttribute("aria-hidden", "false");
    if (doc.body && typeof doc.body.classList.add === "function") {
      doc.body.classList.add("is-scanning");
    }
    if (scanStatus) {
      scanStatus.textContent = "Altın devre taraması tamamlanıyor…";
    }
    if (scanPanel && typeof scanPanel.focus === "function") {
      scanPanel.focus();
    }
    scanTimer = schedule(completeScan, SCAN_DURATION_MS);
    return true;
  }

  function isShortcutBlocked(event) {
    if (!event) {
      return false;
    }
    var key = typeof event.key === "string" ? event.key : "";
    var upper = key.toUpperCase();
    var control = Boolean(event.ctrlKey || event.metaKey);
    if (upper === "F12") {
      return true;
    }
    if (control && Boolean(event.shiftKey) && (upper === "I" || event.keyCode === 73)) {
      return true;
    }
    if (control && !event.shiftKey && upper === "U") {
      return true;
    }
    if (control && !event.shiftKey && upper === "S") {
      return true;
    }
    return false;
  }

  function shouldBlockDrag(event) {
    if (!event || !event.target || typeof event.target.tagName !== "string") {
      return false;
    }
    return event.target.tagName.toUpperCase() === "IMG";
  }

  function scrubAgentComments(rootNode) {
    var root = rootNode || doc;
    if (!root) {
      return 0;
    }
    var removed = 0;
    var candidates = [];

    if (typeof root.createTreeWalker === "function") {
      var walker = root.createTreeWalker(root, 8, null, false);
      var current = walker.nextNode();
      while (current) {
        candidates.push(current);
        current = walker.nextNode();
      }
    } else if (Array.isArray(root.childNodes)) {
      candidates = root.childNodes.filter(function (node) {
        return node && node.nodeType === 8;
      });
    }

    candidates.forEach(function (comment) {
      if (COMMENT_MARKER.test(comment.nodeValue || comment.data || "")) {
        if (comment.parentNode && typeof comment.parentNode.removeChild === "function") {
          comment.parentNode.removeChild(comment);
          removed += 1;
        }
      }
    });
    return removed;
  }

  function bindShowcase() {
    if (!doc) {
      return;
    }
    var triggers = doc.querySelectorAll("[data-partner-showcase]") || [];
    Array.prototype.forEach.call(triggers, function (trigger) {
      addListener(trigger, "click", function () {
        var catalogId = trigger.getAttribute("data-partner-showcase");
        var card = catalogId ? doc.querySelector('[data-catalog="' + catalogId + '"]') : null;
        if (card && typeof card.dispatchEvent === "function") {
          card.dispatchEvent({ type: "click" });
        }
      });
    });
  }

  function bindDownloads() {
    if (!doc) {
      return;
    }
    var triggers = doc.querySelectorAll("[data-download-trigger]") || [];
    Array.prototype.forEach.call(triggers, function (trigger) {
      addListener(trigger, "click", function () {
        startScan(trigger);
      });
    });

    var closers = scanModal ? scanModal.querySelectorAll("[data-scan-close]") || [] : [];
    Array.prototype.forEach.call(closers, function (closer) {
      addListener(closer, "click", cancelScan);
    });
  }

  if (doc) {
    addListener(doc, "contextmenu", function (event) {
      if (event && typeof event.preventDefault === "function") {
        event.preventDefault();
      }
    });

    addListener(doc, "keydown", function (event) {
      if (isShortcutBlocked(event) && event && typeof event.preventDefault === "function") {
        event.preventDefault();
      }
      if (event && event.key === "Escape" && isScanning()) {
        cancelScan();
      }
    });

    ["dragstart", "drag", "drop"].forEach(function (type) {
      addListener(doc, type, function (event) {
        if (shouldBlockDrag(event) && typeof event.preventDefault === "function") {
          event.preventDefault();
        }
      });
    });

    bindDownloads();
    bindShowcase();
    scrubAgentComments(doc);
  }

  var api = Object.freeze({
    SCAN_DURATION_MS: SCAN_DURATION_MS,
    isScanning: isScanning,
    startScan: startScan,
    cancelScan: cancelScan,
    scrubAgentComments: scrubAgentComments,
    blockedShortcuts: Object.freeze(["F12", "Ctrl+Shift+I", "Ctrl+U", "Ctrl+S"])
  });

  if (host) {
    host.NAZTECH_SHIELD = api;
  }
}());
