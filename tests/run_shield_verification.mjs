import { createConsoleSpy, createDocument } from "./dom-shim.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = fs.readFileSync(path.join(ROOT, "security-shield.js"), "utf8");
const RESULTS_PATH = path.join(ROOT, "artifacts", "shield-stress-results.jsonl");
const TOTAL_ITERATIONS = 100;
const SEED = 20261122;

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

function read(relativePath) {
  return fs.readFileSync(path.join(ROOT, relativePath), "utf8");
}

function extractSourceComments(text, language) {
  const found = [];
  const blockPattern = /\/\*[\s\S]*?\*\//g;
  let match = blockPattern.exec(text);
  while (match !== null) {
    found.push(match[0]);
    match = blockPattern.exec(text);
  }
  if (language === "html") {
    const htmlPattern = /<!--[\s\S]*?-->/g;
    match = htmlPattern.exec(text);
    while (match !== null) {
      found.push(match[0]);
      match = htmlPattern.exec(text);
    }
  } else {
    const linePattern = /^[ \t]*\/\/.*$/gm;
    match = linePattern.exec(text);
    while (match !== null) {
      found.push(match[0]);
      match = linePattern.exec(text);
    }
  }
  return found;
}

function runStaticPreflight() {
  const failures = [];
  const checks = [];

  const addCheck = (name, condition, detail) => {
    checks.push({ name, pass: Boolean(condition), detail });
    if (!condition) {
      failures.push(name + ": " + detail);
    }
  };

  const scripts = ["hizmet-detay.js", "tezweb-3d.js", "webgl-3d-viewer.js", "realistic-3d-models.js", "security-shield.js"];
  for (const name of scripts) {
    const result = spawnSync(process.execPath, ["--check", name], {
      cwd: ROOT,
      encoding: "utf8"
    });
    addCheck("node --check " + name, result.status === 0, result.status === 0 ? "syntax OK" : (result.stderr || "syntax failure").trim());
  }

  const html = read("index.html");
  const css = read("style.css");
  const marker = /\b(?:ai|agent|copilot|chatgpt|claude|opencode)\b|generated by/i;
  const sources = [
    ["index.html", html, "html"],
    ["style.css", css, "css"],
    ["hizmet-detay.js", read("hizmet-detay.js"), "js"],
    ["tezweb-3d.js", read("tezweb-3d.js"), "js"],
    ["webgl-3d-viewer.js", read("webgl-3d-viewer.js"), "js"],
    ["realistic-3d-models.js", read("realistic-3d-models.js"), "js"],
    ["security-shield.js", SOURCE, "js"]
  ];

  for (const [name, text, language] of sources) {
    const comments = extractSourceComments(text, language);
    const marked = comments.filter((comment) => marker.test(comment));
    addCheck(name + " scrubbed comments", marked.length === 0, marked.length === 0 ? "no machine-authored comments" : "found " + marked.length);
  }

  const cssBody = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const openBraces = (cssBody.match(/\{/g) || []).length;
  const closeBraces = (cssBody.match(/\}/g) || []).length;
  addCheck("CSS balanced braces", openBraces === closeBraces, openBraces + "/" + closeBraces);
  addCheck("CSS no !important", !/!important/i.test(cssBody), "declaration absent");
  addCheck("CSS scan sweep keyframes", /@keyframes\s+nztScanSweep\b/.test(cssBody) && /1\.5s/.test(cssBody), "1.5s animation present");

  addCheck("HTML download center", html.includes('id="indirme-merkezi"') && html.includes("Resmi İndirme Merkezi"), "section present");
  addCheck("HTML three download triggers", (html.match(/data-download-trigger/g) || []).length === 3, "count=3");
  addCheck("HTML scan modal", html.includes('id="downloadScanModal"') && html.includes("data-scan-close"), "modal present");
  addCheck("HTML security shield linked", html.includes('<script src="security-shield.js" defer></script>'), "classic deferred script present");
  addCheck("HTML sponsor SVG logos", html.includes("partner-marquee__svg") && html.includes("LAVOX") && html.includes("data-partner-showcase=\"5\""), "inline SVG and N2MOBIL showcase present");

  addCheck("Shield keyboard blocks", ["F12", "Ctrl+Shift+I", "Ctrl+U", "Ctrl+S"].every((key) => SOURCE.includes(key)) && SOURCE.includes("contextmenu"), "all shortcuts present");
  addCheck("Shield drag block", ["dragstart", "drag", "drop"].every((type) => SOURCE.includes('"' + type + '"')), "image drag handlers present");
  addCheck("Shield scan duration", /SCAN_DURATION_MS\s*=\s*1500\b/.test(SOURCE), "1500ms constant present");

  return { checks, failures };
}

function addElement(doc, tag, options = {}) {
  const element = doc.createElement(tag);
  if (options.id) element.id = options.id;
  if (options.className) element.className = options.className;
  for (const [name, value] of Object.entries(options.attributes || {})) {
    element.setAttribute(name, value);
  }
  (options.parent || doc.body).appendChild(element);
  return element;
}

function buildFixture(scenario) {
  const doc = createDocument();
  const services = addElement(doc, "section", { id: "hizmetler" });
  const cards = [];
  for (let id = 1; id <= 8; id += 1) {
    cards.push(addElement(doc, "div", {
      className: "card-hover",
      parent: services,
      attributes: { "data-catalog": String(id) }
    }));
  }

  const urls = scenario.invalidUrl
    ? "http://example.invalid/download"
    : "https://www.hikvision.com/en/support/download/software/";
  const trigger = addElement(doc, "button", {
    attributes: {
      "data-download-trigger": "",
      "data-download-url": urls,
      "data-download-label": "Official client"
    }
  });

  const modal = addElement(doc, "div", {
    id: "downloadScanModal",
    attributes: { hidden: "", "aria-hidden": "true", role: "dialog" }
  });
  addElement(doc, "div", { className: "scan-modal__backdrop", parent: modal, attributes: { "data-scan-close": "" } });
  addElement(doc, "div", { className: "scan-modal__panel", parent: modal, attributes: { tabindex: "-1" } });
  addElement(doc, "p", { id: "scanStatus", parent: modal });
  const cancel = addElement(doc, "button", { parent: modal, attributes: { "data-scan-close": "" } });
  const showcase = addElement(doc, "button", { attributes: { "data-partner-showcase": "5" } });
  const image = addElement(doc, "img", { attributes: { src: "img/hikvision_dome.jpg", alt: "camera" } });
  const plain = addElement(doc, "div", {});

  return { doc, cards, trigger, modal, cancel, showcase, image, plain };
}

function buildPlan() {
  const classes = [
    "download-complete", "download-cancel", "download-escape", "invalid-url",
    "contextmenu", "keyboard-block", "keyboard-allow", "image-drag",
    "plain-drag", "showcase", "comment-scrub", "scan-guards"
  ];
  const scenarios = [];
  for (let index = 0; index < TOTAL_ITERATIONS; index += 1) {
    const scenarioClass = classes[index % classes.length];
    scenarios.push({
      iteration: index + 1,
      scenarioClass,
      invalidUrl: scenarioClass === "invalid-url",
      variant: index
    });
  }
  let seed = SEED >>> 0;
  const random = () => {
    seed = (Math.imul(1664525, seed) + 1013904223) >>> 0;
    return seed / 4294967296;
  };
  for (let index = scenarios.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(random() * (index + 1));
    const temporary = scenarios[index];
    scenarios[index] = scenarios[swapIndex];
    scenarios[swapIndex] = temporary;
  }
  assert(scenarios.length === TOTAL_ITERATIONS, "plan length must be 100");
  return scenarios;
}

function flushTimers(timers) {
  timers.filter((timer) => !timer.cancelled).forEach((timer) => timer.callback());
}

function verifyScenario(scenario, fixture, api, timers, opened) {
  const { doc, trigger, modal, cancel, showcase, image, plain, cards } = fixture;

  assert(api.SCAN_DURATION_MS === 1500, "scan duration must be exactly 1500ms");
  assert(Object.isFrozen(api), "public API must be frozen");
  assert(api.blockedShortcuts.length === 4, "four blocked shortcuts expected");

  if (scenario.scenarioClass === "download-complete") {
    assert(api.startScan(trigger) === true, "valid trigger must start the scan");
    assert(api.isScanning() === true, "scan state must be active");
    assert(modal.hidden === false, "scan modal must be visible");
    assert(modal.getAttribute("aria-hidden") === "false", "scan modal aria-hidden must be false");
    assert(doc.body.classList.contains("is-scanning"), "body scan class must be present");
    assert(doc.getElementById("scanStatus").textContent.length > 0, "scan status must be populated");
    assert(timers.some((timer) => timer.delay === 1500 && !timer.cancelled), "1500ms timer must be scheduled");
    flushTimers(timers);
    assert(api.isScanning() === false, "scan must finish after the timer");
    assert(modal.hidden === true, "scan modal must close after the timer");
    assert(!doc.body.classList.contains("is-scanning"), "body scan class must be removed");
    assert(opened.length === 1, "exactly one official link must open");
    return "scan=complete; opened=1; duration=1500ms";
  }

  if (scenario.scenarioClass === "download-cancel") {
    assert(api.startScan(trigger) === true, "scan must start before cancel");
    cancel.dispatchEvent({ type: "click" });
    assert(api.isScanning() === false, "cancel must stop the scan");
    assert(modal.hidden === true, "cancel must hide the scan modal");
    flushTimers(timers);
    assert(opened.length === 0, "cancelled scan must not open a link");
    return "scan=cancelled; opened=0";
  }

  if (scenario.scenarioClass === "download-escape") {
    assert(api.startScan(trigger) === true, "scan must start before Escape");
    doc.dispatchEvent({ type: "keydown", key: "Escape" });
    assert(api.isScanning() === false, "Escape must stop the scan");
    flushTimers(timers);
    assert(opened.length === 0, "Escape must not open a link");
    return "scan=escape; opened=0";
  }

  if (scenario.scenarioClass === "invalid-url") {
    assert(api.startScan(trigger) === false, "insecure URL must be rejected");
    assert(modal.hidden === true, "invalid URL must not open the modal");
    flushTimers(timers);
    assert(opened.length === 0, "invalid URL must not open a link");
    return "url=rejected; modal=hidden";
  }

  if (scenario.scenarioClass === "contextmenu") {
    assert(doc.dispatchEvent({ type: "contextmenu" }) === false, "right-click must be prevented");
    return "contextmenu=blocked";
  }

  if (scenario.scenarioClass === "keyboard-block") {
    const shortcuts = [
      { key: "F12" },
      { key: "i", ctrlKey: true, shiftKey: true },
      { key: "u", ctrlKey: true },
      { key: "s", ctrlKey: true }
    ];
    for (const shortcut of shortcuts) {
      assert(doc.dispatchEvent({ type: "keydown", ...shortcut }) === false, "shortcut must be prevented: " + shortcut.key);
    }
    return "shortcuts=4/4 blocked";
  }

  if (scenario.scenarioClass === "keyboard-allow") {
    assert(doc.dispatchEvent({ type: "keydown", key: "a" }) === true, "ordinary keys must remain usable");
    assert(doc.dispatchEvent({ type: "keydown", key: "s", shiftKey: true }) === true, "Shift+S must remain usable");
    return "ordinary-keys=allowed";
  }

  if (scenario.scenarioClass === "image-drag") {
    for (const type of ["dragstart", "drag", "drop"]) {
      assert(image.dispatchEvent({ type }) === false, "image " + type + " must be prevented");
    }
    return "image-drag=3/3 blocked";
  }

  if (scenario.scenarioClass === "plain-drag") {
    assert(plain.dispatchEvent({ type: "dragstart" }) === true, "non-image drag must stay allowed");
    return "plain-drag=allowed";
  }

  if (scenario.scenarioClass === "showcase") {
    let openedCatalog = 0;
    cards[4].addEventListener("click", () => { openedCatalog += 1; });
    showcase.dispatchEvent({ type: "click" });
    assert(openedCatalog === 1, "showcase must open catalog 5 exactly once");
    return "showcase=catalog-5";
  }

  if (scenario.scenarioClass === "comment-scrub") {
    let removedNode = null;
    const parent = {
      removeChild(node) {
        removedNode = node;
      }
    };
    const comments = [
      { nodeType: 8, nodeValue: "AI generated helper", parentNode: parent },
      { nodeType: 8, nodeValue: "Baysöz Yazılım", parentNode: parent }
    ];
    const fakeRoot = {
      createTreeWalker() {
        let cursor = -1;
        return {
          nextNode() {
            cursor += 1;
            return cursor < comments.length ? comments[cursor] : null;
          }
        };
      }
    };
    assert(api.scrubAgentComments(fakeRoot) === 1, "exactly one marked comment must be removed");
    assert(removedNode === comments[0], "the marked comment must be the removed node");
    return "scrub=1 removed, 1 retained";
  }

  assert(api.isScanning() === false, "guards scenario must start idle");
  assert(api.startScan(trigger) === true, "guards scenario must start a scan");
  assert(api.startScan(trigger) === false, "second scan must be rejected while active");
  api.cancelScan();
  assert(api.isScanning() === false, "cancel must clear scan state");
  return "guards=double-start rejected";
}

function main() {
  const preflight = runStaticPreflight();
  for (const check of preflight.checks) {
    console.log("PREFLIGHT " + (check.pass ? "PASS" : "FAIL") + " | " + check.name + " | " + check.detail);
  }
  if (preflight.failures.length > 0) {
    fs.writeFileSync(RESULTS_PATH, "");
    console.log("PREFLIGHT_ABORT=" + preflight.failures.length);
    console.log("TOTAL_RUNS=100 PASS=0 FAIL=100");
    console.log("STRESS_VERDICT_SHIELD: 0/100 PASS");
    process.exit(1);
  }

  const plan = buildPlan();
  fs.writeFileSync(RESULTS_PATH, "");
  let passed = 0;
  let failed = 0;

  for (const scenario of plan) {
    const fixture = buildFixture(scenario);
    const consoleSpy = createConsoleSpy();
    const timers = [];
    const opened = [];
    const sandbox = {
      window: {
        addEventListener() {},
        removeEventListener() {},
        setTimeout(callback, delay) {
          timers.push({ id: timers.length + 1, callback, delay, cancelled: false });
          return timers.length;
        },
        clearTimeout(id) {
          const timer = timers.find((entry) => entry.id === id);
          if (timer) {
            timer.cancelled = true;
          }
        },
        open(url) {
          opened.push(url);
          return {};
        }
      },
      document: fixture.doc,
      console: consoleSpy
    };

    let detail = "";
    let pass = false;
    try {
      vm.runInNewContext(SOURCE, sandbox, { filename: "security-shield.js", timeout: 5000 });
      const api = sandbox.window.NAZTECH_SHIELD;
      detail = verifyScenario(scenario, fixture, api, timers, opened);
      assert(consoleSpy.errorCount === 0, "console.error must stay silent");
      pass = true;
    } catch (error) {
      detail = "FAIL: " + (error && error.message ? error.message : String(error));
    }

    fs.appendFileSync(
      RESULTS_PATH,
      JSON.stringify({
        iteration: scenario.iteration,
        scenario_class: scenario.scenarioClass,
        pass,
        console_errors: consoleSpy.errorCount,
        detail
      }) + "\n"
    );
    if (pass) {
      passed += 1;
    } else {
      failed += 1;
    }
    console.log(
      "RUN " + String(scenario.iteration).padStart(3, "0") +
      " " + (pass ? "PASS" : "FAIL") +
      " | class=" + scenario.scenarioClass +
      " | errors=" + consoleSpy.errorCount +
      " | " + detail
    );
  }

  console.log("TOTAL_RUNS=" + TOTAL_ITERATIONS + " PASS=" + passed + " FAIL=" + failed);
  console.log("STRESS_VERDICT_SHIELD: " + passed + "/" + TOTAL_ITERATIONS + " PASS");
  if (passed !== TOTAL_ITERATIONS || failed !== 0) {
    process.exit(1);
  }
}

main();
